//go:build promptcapture

package main

// Test-only inference recorder. It is compiled only with `-tags promptcapture`,
// so a production build cannot install or expose it. Messages are held in
// memory; nothing is written to disk and no request leaves the process.

import (
	"fmt"
	"os"
	"strings"
	"sync"

	"howl-chat/internal/backend/llama"
	appruntime "howl-chat/internal/runtime"
)

type promptCapture struct {
	inner   appruntime.Client
	mu      sync.Mutex
	last    []llama.ChatMessage
	calls   int
	require []string
	forbid  []string
}

func wrapInferenceCapture(inner appruntime.Client) appruntime.Client {
	capture := &promptCapture{
		inner:   inner,
		require: splitMarkers(os.Getenv("HOWL_CAPTURE_REQUIRE")),
		forbid:  splitMarkers(os.Getenv("HOWL_CAPTURE_FORBID")),
	}
	fmt.Printf("[prompt-capture] recorder armed require=%d forbid=%d\n", len(capture.require), len(capture.forbid))
	return capture
}

func splitMarkers(value string) []string {
	var markers []string
	for _, marker := range strings.Split(value, ",") {
		if marker = strings.TrimSpace(marker); marker != "" {
			markers = append(markers, marker)
		}
	}
	return markers
}

func (c *promptCapture) record(messages []llama.ChatMessage) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.last = append([]llama.ChatMessage(nil), messages...)
	c.calls++

	// Audit markers come from the test environment. Only booleans are printed so
	// the captured prompt itself never leaves memory.
	if len(c.require) > 0 || len(c.forbid) > 0 {
		var joined strings.Builder
		for _, message := range c.last {
			if content, ok := message.Content.(string); ok {
				joined.WriteString(content)
				joined.WriteString("\n")
			}
		}
		text := joined.String()
		requireOK := true
		for _, marker := range c.require {
			if !strings.Contains(text, marker) {
				requireOK = false
			}
		}
		forbidClear := true
		for _, marker := range c.forbid {
			if strings.Contains(text, marker) {
				forbidClear = false
			}
		}
		fmt.Printf("[prompt-capture] call=%d messages=%d require_ok=%t forbid_clear=%t\n", c.calls, len(c.last), requireOK, forbidClear)
	}
}

func (c *promptCapture) GenerateChat(messages []llama.ChatMessage, options *llama.InferenceOptions) (string, error) {
	c.record(messages)
	return c.reply(), nil
}

func (c *promptCapture) GenerateChatStream(messages []llama.ChatMessage, options *llama.InferenceOptions, callback llama.TokenCallback) error {
	c.record(messages)
	callback(c.reply(), false)
	callback("", true)
	return nil
}

func (c *promptCapture) GenerateChatStreamWithImage(messages []llama.ChatMessage, imageData []byte, options *llama.InferenceOptions, callback llama.TokenCallback) error {
	c.record(messages)
	callback(c.reply(), false)
	callback("", true)
	return nil
}

func (c *promptCapture) CancelRequest() {
	if c.inner != nil {
		c.inner.CancelRequest()
	}
}

// GetContextSize stays large enough that lore budgets use their normal floor.
func (c *promptCapture) GetContextSize() int { return 4096 }

func (c *promptCapture) GetLoadedModel() (map[string]interface{}, error) {
	return map[string]interface{}{"id": "prompt-capture", "name": "Prompt capture recorder"}, nil
}

func (c *promptCapture) Health() error { return nil }

func (c *promptCapture) IsLoaded() bool { return true }

func (c *promptCapture) reply() string {
	return "[capture] This reply is generated by the test-only inference recorder."
}

// GetPromptCapture reports the messages seen at the inference boundary. It is
// available only in a promptcapture build; prompts stay in memory.
func (a *App) GetPromptCapture() map[string]interface{} {
	capture, ok := a.engine.Client().(*promptCapture)
	if !ok {
		return map[string]interface{}{"enabled": false}
	}
	capture.mu.Lock()
	defer capture.mu.Unlock()
	messages := make([]map[string]interface{}, 0, len(capture.last))
	for _, message := range capture.last {
		content, _ := message.Content.(string)
		messages = append(messages, map[string]interface{}{"role": message.Role, "content": content})
	}
	return map[string]interface{}{
		"enabled":  true,
		"calls":    capture.calls,
		"messages": messages,
	}
}
